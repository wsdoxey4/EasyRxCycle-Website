// Writes the guide -> lead kit map used by the download email (functions/api/_guideKits.js) and the portal's
// lead-magnet drip (supabase/functions/_shared/guide-kits.ts). Same pick as each guide page's "See the kit" box.
// Run after adding a guide or changing kit prices:  npx tsx --tsconfig tsconfig.json scripts/gen-guide-kits.ts
import { writeFileSync } from "node:fs";
import { MAGNETS } from "@/lib/leadMagnets";
import { GUIDE_BODIES } from "@/lib/guideBodies";
import { kitsForGuide } from "@/lib/guideKits";

const NO_KIT = new Set(["capability-statement", "line-card", "sample-certificate-of-destruction"]);
const kits: Record<string, { name: string; href: string; from: string | null }> = {};
const guides: Record<string, string> = {};   // slug and h1 -> kit cat
for (const m of MAGNETS) {
  if (NO_KIT.has(m.slug)) continue;
  const body = m.body ?? GUIDE_BODIES[m.slug];
  const k = kitsForGuide([m.intro, ...m.bullets, ...(body ?? []).map((b) => b.h + " " + b.p)].join(" "), m.slug).find((x) => x.cat !== "medication-onsite");
  if (!k) continue;
  kits[k.cat] = { name: k.name, href: k.href, from: k.from };
  guides[m.slug] = k.cat;
  guides[m.h1.toLowerCase()] = k.cat;
}
const out = JSON.stringify({ kits, guides }, null, 1);
const head = "// GENERATED by easyrxcycle-web/scripts/gen-guide-kits.ts — do not edit by hand.\n";
writeFileSync("functions/api/_guideKits.js", `${head}export const GUIDE_KITS = ${out};\n`);
writeFileSync("../easyrxcycle-portal/supabase/functions/_shared/guide-kits.ts", `${head}export const GUIDE_KITS: { kits: Record<string, { name: string; href: string; from: string | null }>; guides: Record<string, string> } = ${out};\n`);
console.log(Object.keys(guides).length / 2, "guides;", Object.entries(kits).map(([c, k]) => `${c} ${k.from}`).join(", "));
const tally: Record<string, number> = {}; for (const [s, c] of Object.entries(guides)) if (!s.includes(" ")) tally[c] = (tally[c] || 0) + 1; console.log(tally);
