// Builds the site assistant's kit catalog from the site's own product data (lib/shop.ts, lib/shopContent.ts,
// lib/pdpExtras.ts) so prices and kit facts in the chat never drift from the website.
// Run after any price or kit-copy change:  npx tsx scripts/build-assistant-facts.ts
// Writes ../easyrxcycle-portal/supabase/functions/site-assistant/catalog.ts, then redeploy the site-assistant function.
import { writeFileSync } from "node:fs";
import { PRODUCTS, CATEGORIES, money, autoshipCents, FREE_SHIP_THRESHOLD_CENTS, FLAT_SHIP_CENTS } from "../lib/shop";
import { KITS } from "../lib/shopContent";
import { PDP_EXTRAS } from "../lib/pdpExtras";

// The on-site kit is only for WASTED partial doses (William 2026-10-30). The assistant never recommends it.
const HIDDEN = new Set(["medication-onsite"]);

const kits = KITS.filter((k) => !HIDDEN.has(k.category)).map((k) => {
  const cat = CATEGORIES.find((c) => c.key === k.category);
  const x = PDP_EXTRAS[k.category] || ({} as (typeof PDP_EXTRAS)[string]);
  const sizes = PRODUCTS.filter((p) => p.category === k.category).map((p) => ({
    sku: p.sku, size: p.size, cents: p.cents, autoship_cents: autoshipCents(p.cents), best_for: x.bestFor?.[p.size] || null,
  }));
  return {
    category: k.category, name: k.name, url: `/shop/${k.slug}/`, image: cat?.image || null,
    summary: k.intro, accepts: x.accepts || null, not_for: x.notFor || null, includes: k.included, who_for: k.whoFor,
    best_value: x.bestValue || null, faqs: k.faqs, sizes,
  };
});

const lines: string[] = [];
for (const k of kits) {
  lines.push(`## ${k.name} (${k.url})`);
  lines.push(k.summary);
  if (k.accepts) lines.push(`Accepts: ${k.accepts}.`);
  if (k.not_for) lines.push(`Not for: ${k.not_for}.`);
  lines.push(`Who it's for: ${k.who_for}`);
  lines.push(`In the kit: ${k.includes.join("; ")}.`);
  lines.push("Sizes (one-time price / auto-ship price, SKU):");
  for (const s of k.sizes) lines.push(`- ${s.size}: ${money(s.cents)} / ${money(s.autoship_cents)} auto-ship, ${s.sku}${s.best_for ? ` (best for: ${s.best_for})` : ""}${k.best_value === s.size ? " (best value)" : ""}`);
  for (const f of k.faqs) {
    // The site's mail-back vs on-site FAQ pitches the on-site kit; the assistant never does.
    if (/on-site kit/i.test(f.a)) continue;
    lines.push(`Q: ${f.q} A: ${f.a}`);
  }
  lines.push("");
}
lines.push(`Shipping: free outbound shipping on orders over ${money(FREE_SHIP_THRESHOLD_CENTS)}, otherwise a flat ${money(FLAT_SHIP_CENTS)}. Return shipping is always prepaid. Auto-ship orders always ship free and get 20% off.`);
lines.push("Expedite: controlled substance kits can be expedited for +$250.");

const out = `// GENERATED by easyrxcycle-web/scripts/build-assistant-facts.ts on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
export const CATALOG_TEXT = ${JSON.stringify(lines.join("\n"))};
export type Size = { sku: string; size: string; cents: number; autoship_cents: number; best_for: string | null };
export type Kit = { category: string; name: string; url: string; image: string | null; sizes: Size[] };
export const KITS: Kit[] = ${JSON.stringify(kits.map(({ category, name, url, image, sizes }) => ({ category, name, url, image, sizes })))};
`;
const dest = new URL("../../easyrxcycle-portal/supabase/functions/site-assistant/catalog.ts", import.meta.url);
writeFileSync(dest, out);
console.log(`wrote ${kits.length} kits, ${kits.reduce((n, k) => n + k.sizes.length, 0)} sizes, ${lines.join("\n").length} chars`);
